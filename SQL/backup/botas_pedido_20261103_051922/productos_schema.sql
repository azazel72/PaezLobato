CREATE TABLE `productos` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `tipo` enum('FONDO','VASO','BOTA') NOT NULL,
  `tipo_producto_id` int(11) DEFAULT NULL,
  `material_id` int(11) DEFAULT NULL,
  `tostado_id` int(11) DEFAULT NULL,
  `ubicacion_id` int(11) DEFAULT NULL,
  `contenedor_id` int(11) DEFAULT NULL,
  `codigo` varchar(60) NOT NULL,
  `produccion_id` int(11) DEFAULT NULL,
  `estado` int(11) DEFAULT 1,
  `created_at` timestamp NOT NULL DEFAULT current_timestamp(),
  `updated_at` timestamp NOT NULL DEFAULT current_timestamp() ON UPDATE current_timestamp(),
  `deleted_at` timestamp NULL DEFAULT NULL,
  `is_deleted` tinyint(1) NOT NULL DEFAULT 0,
  `created_by` varchar(100) NOT NULL DEFAULT 'system',
  `updated_by` varchar(100) NOT NULL DEFAULT 'system',
  `deleted_by` varchar(100) DEFAULT NULL,
  `fabricado_por_id` int(11) DEFAULT NULL,
  `pedido_id` int(11) NOT NULL DEFAULT 0,
  `pedido_fabricacion_id` int(11) NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`),
  KEY `idx_productos_produccion` (`produccion_id`),
  KEY `fk_productos_materiales` (`material_id`),
  KEY `idx_productos_estado` (`estado`),
  KEY `idx_productos_tipo_producto_id` (`tipo_producto_id`),
  KEY `idx_productos_ubicacion_id` (`ubicacion_id`),
  KEY `idx_productos_contenedor_id` (`contenedor_id`),
  KEY `fk_productos_tostado` (`tostado_id`),
  KEY `idx_producto_pedido_estado` (`pedido_id`,`estado`,`is_deleted`),
  CONSTRAINT `fk_productos_contenedores` FOREIGN KEY (`contenedor_id`) REFERENCES `contenedores` (`id`) ON UPDATE CASCADE,
  CONSTRAINT `fk_productos_estados_entidad` FOREIGN KEY (`estado`) REFERENCES `estados_productos` (`id`) ON UPDATE CASCADE,
  CONSTRAINT `fk_productos_materiales` FOREIGN KEY (`material_id`) REFERENCES `materiales` (`id`) ON UPDATE CASCADE,
  CONSTRAINT `fk_productos_tipos_producto` FOREIGN KEY (`tipo_producto_id`) REFERENCES `tipos_producto` (`id`) ON UPDATE CASCADE,
  CONSTRAINT `fk_productos_tostado` FOREIGN KEY (`tostado_id`) REFERENCES `tostados` (`id`),
  CONSTRAINT `fk_productos_ubicaciones` FOREIGN KEY (`ubicacion_id`) REFERENCES `ubicaciones` (`id`) ON UPDATE CASCADE
) ENGINE=InnoDB AUTO_INCREMENT=6839 DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
