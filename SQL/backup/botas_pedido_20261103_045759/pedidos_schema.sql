CREATE TABLE `pedidos` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `numero` varchar(50) NOT NULL,
  `destino` varchar(20) NOT NULL DEFAULT 'CLIENTE',
  `cliente_id` int(11) DEFAULT NULL,
  `tipo_producto_id` int(11) DEFAULT NULL,
  `material_id` int(11) DEFAULT NULL,
  `tostado_id` int(11) DEFAULT NULL,
  `cantidad` int(11) NOT NULL DEFAULT 0,
  `cantidad_fabricada` int(11) NOT NULL,
  `descripcion` varchar(120) NOT NULL DEFAULT '',
  `fecha` date DEFAULT NULL,
  `fecha_finalizacion` date DEFAULT NULL,
  `estado` int(11) DEFAULT 1,
  `created_at` timestamp NOT NULL DEFAULT current_timestamp(),
  `updated_at` timestamp NOT NULL DEFAULT current_timestamp() ON UPDATE current_timestamp(),
  `deleted_at` timestamp NULL DEFAULT NULL,
  `is_deleted` tinyint(1) NOT NULL DEFAULT 0,
  `created_by` varchar(100) NOT NULL DEFAULT 'system',
  `updated_by` varchar(100) NOT NULL DEFAULT 'system',
  `deleted_by` varchar(100) DEFAULT NULL,
  PRIMARY KEY (`id`),
  KEY `fk_ordenes_fabricacion_estados` (`estado`),
  KEY `idx_pedidos_cliente_id` (`cliente_id`),
  KEY `fk_pedidos_tostado` (`tostado_id`),
  CONSTRAINT `fk_ordenes_fabricacion_estados_entidad` FOREIGN KEY (`estado`) REFERENCES `estados_pedidos` (`id`) ON UPDATE CASCADE,
  CONSTRAINT `fk_pedidos_clientes` FOREIGN KEY (`cliente_id`) REFERENCES `clientes` (`id`) ON UPDATE CASCADE,
  CONSTRAINT `fk_pedidos_tostado` FOREIGN KEY (`tostado_id`) REFERENCES `tostados` (`id`)
) ENGINE=InnoDB AUTO_INCREMENT=22 DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
