CREATE TABLE `fabricacion_semanal` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `pedido_id` int(11) NOT NULL,
  `tipo_producto_id` int(11) NOT NULL,
  `material_id` int(11) DEFAULT NULL,
  `tostado_id` int(11) DEFAULT NULL,
  `cantidad` int(11) NOT NULL DEFAULT 0,
  `cantidad_fabricada` int(11) NOT NULL DEFAULT 0,
  `fecha_inicio` date DEFAULT NULL,
  `estado` int(11) DEFAULT 1,
  `created_at` timestamp NOT NULL DEFAULT current_timestamp(),
  `updated_at` timestamp NOT NULL DEFAULT current_timestamp() ON UPDATE current_timestamp(),
  `deleted_at` timestamp NULL DEFAULT NULL,
  `is_deleted` tinyint(1) NOT NULL DEFAULT 0,
  `created_by` varchar(100) NOT NULL DEFAULT 'system',
  `updated_by` varchar(100) NOT NULL DEFAULT 'system',
  `deleted_by` varchar(100) DEFAULT NULL,
  PRIMARY KEY (`id`),
  KEY `fk_lineas_fabricacion_ordenes` (`pedido_id`),
  KEY `fk_lineas_fabricacion_tipos` (`tipo_producto_id`),
  KEY `fk_lineas_fabricacion_estados` (`estado`),
  KEY `fk_lineas_fabricacion_materiales` (`material_id`),
  KEY `idx_fabricacion_semanal_pedido_id` (`pedido_id`),
  KEY `fk_fabricacion_semanal_tostado` (`tostado_id`),
  CONSTRAINT `fk_fabricacion_semanal_pedidos` FOREIGN KEY (`pedido_id`) REFERENCES `pedidos` (`id`) ON UPDATE CASCADE,
  CONSTRAINT `fk_fabricacion_semanal_tostado` FOREIGN KEY (`tostado_id`) REFERENCES `tostados` (`id`),
  CONSTRAINT `fk_lineas_fabricacion_estados_entidad` FOREIGN KEY (`estado`) REFERENCES `estados_fabricacion_semanal` (`id`) ON UPDATE CASCADE,
  CONSTRAINT `fk_lineas_fabricacion_materiales` FOREIGN KEY (`material_id`) REFERENCES `materiales` (`id`) ON UPDATE CASCADE,
  CONSTRAINT `fk_lineas_fabricacion_ordenes` FOREIGN KEY (`pedido_id`) REFERENCES `pedidos` (`id`) ON UPDATE CASCADE,
  CONSTRAINT `fk_lineas_fabricacion_tipos` FOREIGN KEY (`tipo_producto_id`) REFERENCES `tipos_producto` (`id`) ON UPDATE CASCADE
) ENGINE=InnoDB AUTO_INCREMENT=48 DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
