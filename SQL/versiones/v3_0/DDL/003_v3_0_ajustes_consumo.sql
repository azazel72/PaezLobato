-- Auditoría de reasignaciones y desperdicio. No modifica datos ni la versión de BBDD.
CREATE TABLE IF NOT EXISTS `a_ajustes_consumo` (
  `id` bigint(20) unsigned NOT NULL AUTO_INCREMENT,
  `grupo` char(32) NOT NULL,
  `orden` int(10) unsigned NOT NULL,
  `tipo` enum('reasignacion','desperdicio') NOT NULL DEFAULT 'reasignacion',
  `origen_id` int(11) NOT NULL,
  `destino_id` int(11) DEFAULT NULL,
  `codigo_origen` varchar(60) NOT NULL,
  `codigo_destino` varchar(60) DEFAULT NULL,
  `cantidad` decimal(10,4) NOT NULL,
  `consumido_origen_antes` decimal(10,4) NOT NULL,
  `consumido_origen_despues` decimal(10,4) NOT NULL,
  `consumido_destino_antes` decimal(10,4) DEFAULT NULL,
  `consumido_destino_despues` decimal(10,4) DEFAULT NULL,
  `usuario_id` int(11) DEFAULT NULL,
  `motivo` varchar(255) NOT NULL,
  `created_at` timestamp NOT NULL DEFAULT current_timestamp(),
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_ajuste_grupo_orden` (`grupo`,`orden`),
  KEY `idx_ajuste_origen_fecha` (`origen_id`,`created_at`),
  KEY `idx_ajuste_destino_fecha` (`destino_id`,`created_at`),
  CONSTRAINT `chk_ajuste_cantidad` CHECK (`tipo` = 'reasignacion' and `cantidad` > 0 or `tipo` = 'desperdicio' and `cantidad` <> 0),
  CONSTRAINT `chk_ajuste_lotes` CHECK (`origen_id` > 0 and (`tipo` = 'reasignacion' and `destino_id` is not null and `destino_id` > 0 and `origen_id` <> `destino_id` or `tipo` = 'desperdicio' and `destino_id` is null and `codigo_destino` is null)),
  CONSTRAINT `chk_ajuste_origen` CHECK (`consumido_origen_antes` >= 0 and `consumido_origen_despues` >= 0 and (`tipo` = 'reasignacion' and `consumido_origen_antes` - `consumido_origen_despues` = `cantidad` or `tipo` = 'desperdicio' and `consumido_origen_despues` - `consumido_origen_antes` = `cantidad`)),
  CONSTRAINT `chk_ajuste_destino` CHECK (`tipo` = 'reasignacion' and `consumido_destino_antes` is not null and `consumido_destino_despues` is not null and `consumido_destino_antes` >= 0 and `consumido_destino_despues` - `consumido_destino_antes` = `cantidad` or `tipo` = 'desperdicio' and `consumido_destino_antes` is null and `consumido_destino_despues` is null)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
